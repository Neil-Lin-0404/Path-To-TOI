/*
 * 主文（直覺＋理論＋模板）：FloydWarshall.md
 * ============================================================
 *  Floyd-Warshall 全點對最短路 —— 可編譯副本
 * ============================================================
 *
 * 【一句話】
 *   算出「每一對點」i→j 的最短距離。允許負邊。
 *   方法：枚舉中繼點 k，試著走 i→…→k→…→j。
 *
 * 【跟前兩種哪裡不一樣？】
 *   Dijkstra / Bellman-Ford：一個起點 → dist[u]（一維筆記本）
 *   Floyd：所有起點、所有終點 → dist[i][j]（二維筆記本）
 *
 * 【核心式】
 *   dist[i][j] = min(dist[i][j], dist[i][k] + dist[k][j])
 *   意思：本來直走（或不經 k）的路，跟「先到 k 再到 j」比，誰便宜用誰。
 *
 * 【步驟】
 *   1. 矩陣初始化：
 *        dist[i][i] = 0
 *        有邊 i→j 權 w → dist[i][j] = w（多條邊取較小）
 *        其餘 = INF
 *   2. for k = 1..n
 *        for i = 1..n
 *          for j = 1..n
 *            試經由 k 更新 dist[i][j]
 *   3. 若某 dist[i][i] < 0 → 點 i 在負環上（或可走到負環）
 *
 * 【輸入】
 *   第一行：n m（點數、邊數），點 1..n
 *   接下來 m 行：u v w（有向邊；可負）
 *   輸出：n 行，每行 n 個數 = dist[i][1..n]
 *         不可達印 -1；若偵測到負環，第一行印 NEGATIVE CYCLE 後結束
 *
 * 【複雜度】O(n³)。n 大約 ≤ 400～500 才常用。
 * 【何時用】要全點對、或 n 很小；單源正權仍優先 Dijkstra。
 */

#include <bits/stdc++.h>
using namespace std;

int main()
{
    int n, m;
    cin >> n >> m;

    const long long INF = 4e18;
    // dist[i][j] = 從 i 到 j 目前知道的最短邊權和
    vector<vector<long long>> dist(n + 1, vector<long long>(n + 1, INF));
    for (int i = 1; i <= n; i++)
        dist[i][i] = 0;

    for (int e = 0; e < m; e++)
    {
        int u, v;
        long long w;
        cin >> u >> v >> w;
        // 平行邊取較小；邊權寫進矩陣後就凍住（之後只改 dist 裡「路徑和」）
        dist[u][v] = min(dist[u][v], w);
        // 無向圖再：dist[v][u] = min(dist[v][u], w);
    }

    // ---------- 三層迴圈：允許的中繼點集合逐漸變大 ----------
    // k = 目前「允許當成中繼」的最高編號點（直觀版）
    for (int k = 1; k <= n; k++)
    {
        for (int i = 1; i <= n; i++)
        {
            if (dist[i][k] == INF)
                continue; // i 走不到 k，經 k 沒意義
            for (int j = 1; j <= n; j++)
            {
                if (dist[k][j] == INF)
                    continue;
                // 防 INF 相加溢位：上面已跳過 INF
                if (dist[i][j] > dist[i][k] + dist[k][j])
                    dist[i][j] = dist[i][k] + dist[k][j];
            }
        }
    }

    // ---------- 負環：對角線變負 ----------
    for (int i = 1; i <= n; i++)
    {
        if (dist[i][i] < 0)
        {
            cout << "NEGATIVE CYCLE\n";
            return 0;
        }
    }

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            if (dist[i][j] == INF)
                cout << -1;
            else
                cout << dist[i][j];
            cout << (j == n ? '\n' : ' ');
        }
    }
}

