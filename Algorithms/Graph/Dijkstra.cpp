/*
 * 主文（直覺＋理論＋模板）：Dijkstra.md
 * ============================================================
 *  Dijkstra 最短路 —— 可編譯副本
 * ============================================================
 *
 * 【一句話】
 *   邊權都是「正數」時，從起點 1 走到每個點的最短距離。
 *   規則：永遠先處理「目前距離最小」的那個點，再用它去更新鄰居。
 *
 * 【為什麼不能用普通 BFS？】
 *   BFS 假設「先走到的一定比較近」。這只在「每條邊長度都是 1」時成立。
 *
 *   反例（邊上都是權重）：
 *
 *         2          10
 *     1 -----> 2 --------> 4
 *      \       |          /
 *       \ 5    | 1       / 1
 *        \     v        /
 *         ----> 3 -----
 *
 *   若用 BFS（把邊當一步）：1→3→4 只要 2 步，看起來比 1→2→3→4 的 3 步近。
 *   但真實花費：
 *     1→3→4     = 5+1 = 6
 *     1→2→3→4   = 2+1+1 = 4  ← 才是最短
 *
 *   邊權不全是 1 時，「步數少」≠「比較近」。
 *   邊權全是 1 → BFS；邊權只有 0/1 → 0-1 BFS（deque）；正權重 → Dijkstra。
 *   （負權重這份不講，那要用 Bellman-Ford / SPFA 一族。）
 *
 * 【核心動作：鬆弛（relax）】
 *   dist[v] = 目前知道「從 1 到 v」的最短距離（一開始除了起點都是 INF）。
 *   看一條邊 u → v（權重 w）：
 *     若 dist[u] + w < dist[v]，就把 dist[v] 改成 dist[u]+w。
 *   意思：走 u 再走這條邊，比舊路更好。
 *
 * 【演算法步驟】
 *   1. dist[起點]=0，其餘 INF
 *   2. 把 {距離, 點} 丟進「小根堆」priority_queue（永遠先拿距離最小的）
 *   3. 取出目前距離最小的點 u（這格以後不會再變小 —— 正權時保證）
 *   4. 用 u 鬆弛所有鄰居；若鄰居變短了，再 push 進堆
 *   5. 重複直到堆空
 *
 * 【必背坑：過期狀態】
 *   C++ 的 priority_queue 不能刪舊的。同一點可能被 push 很多次：
 *     先 push {5, 2}，後來找到更好的 dist[2]=3，再 push {3, 2}
 *   堆裡還留著舊的 {5,2}。取出時若 d > dist[u]，代表這筆是過期垃圾 → continue。
 *   沒寫這行會多鬆弛一堆沒用的邊，甚至邏輯錯。
 *
 * 【輸入假設（對齊 CSES Shortest Routes I 風格）】
 *   第一行：n m（點數、邊數），點編號 1..n，起點固定為 1
 *   接下來 m 行：u v w（有向邊 u→v，權重 w）
 *   輸出：dist[1] dist[2] ... dist[n]
 *
 * 【複雜度】
 *   每個點最多被「定案」一次；每條邊最多觸發一次有效鬆弛。
 *   用 binary heap：約 O((n+m) log n)。（同一點可能被 push 多次，所以 log 裡實際是「堆裡狀態數」。）
 */

#include <bits/stdc++.h>
using namespace std;

int main()
{
    // ---------- 讀圖 ----------
    // n = 點數，m = 邊數
    int n, m;
    cin >> n >> m;

    // 鄰接表：graph[u] = { {v, w}, ... } 表示有向邊 u --w--> v
    // 用 pair<到哪, 權重>。點從 1 開始，所以開 n+1。
    vector<vector<pair<int, int>>> graph(n + 1);
    for (int i = 0; i < m; i++)
    {
        int u, v, w;
        cin >> u >> v >> w;
        graph[u].push_back({v, w});
        // 若題目是「無向圖」，還要再加：graph[v].push_back({u, w});
    }

    // ---------- 初始化距離 ----------
    // dist[i] = 從 1 走到 i 的最短距離。還沒走到的先設成「無窮大」。
    // 用 long long + 很大的常數比較安全：很多題權重加總會超過 INT_MAX。
    const long long INF = 4e18;
    vector<long long> dist(n + 1, INF);
    dist[1] = 0; // 起點到自己距離 0

    // ---------- 小根堆 ----------
    // pair = {目前距離, 點編號}
    // priority_queue 預設是「大根堆」（大的先出），最短路要「小的先出」→ greater<>
    // 寫法：priority_queue<型別, 底層容器, 比較方式>
    priority_queue<pair<long long, int>,
                   vector<pair<long long, int>>,
                   greater<pair<long long, int>>>
        pq;

    // 從起點開始：距離 0、點 1
    pq.push({0, 1});

    // ---------- 主迴圈 ----------
    while (!pq.empty())
    {
        // 取出「目前堆裡距離最小」的狀態
        auto [d, u] = pq.top();
        pq.pop();

        // ★ 過期狀態：這筆距離 d 已經不是 dist[u] 的最新值
        //   例如：以前 push 過 {5,u}，後來又找到 {3,u} 並更新 dist[u]=3，
        //   現在才輪到舊的 {5,u} → 直接丟掉。
        if (d > dist[u])
            continue;

        // 走到這裡：d == dist[u]，這是「第一次」以最終最短距離處理 u。
        // （正權圖保證：第一次從堆裡以最小距離取出 u 時，dist[u] 已是答案。）

        // 用 u 去鬆弛所有出去的邊
        for (auto [v, w] : graph[u])
        {
            // 若「經由 u 再走 w」比原本到 v 更短 → 更新
            if (dist[v] > dist[u] + w)
            {
                dist[v] = dist[u] + w;
                // 把新距離丟進堆。舊的較差狀態留在堆裡沒關係，之後會被 continue 掉。
                pq.push({dist[v], v});
            }
        }
    }

    // ---------- 輸出 ----------
    // 若某點不可達，這份範例仍印 INF（實戰要看題目：常改印 -1）
    for (int i = 1; i <= n; i++)
    {
        if (dist[i] == INF)
            cout << -1; // 常見寫法：到不了印 -1；若題目保證連通可改回印 dist[i]
        else
            cout << dist[i];
        cout << (i == n ? '\n' : ' ');
    }
}

