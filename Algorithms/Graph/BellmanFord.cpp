/*
 * 主文（直覺＋理論＋模板）：BellmanFord.md
 * ============================================================
 *  Bellman-Ford 最短路 —— 可編譯副本
 * ============================================================
 *
 * 【一句話】
 *   對「每一條邊」反覆做鬆弛；正權、負權都行。
 *   不做 priority_queue，也不挑「目前最近的點」。
 *
 * 【跟 Dijkstra 哪裡一樣？】
 *   鬆弛式子完全一樣：
 *     if (dist[u] + w < dist[v]) dist[v] = dist[u] + w;
 *   邊權只讀不改；改的永遠是 dist。
 *
 * 【跟 Dijkstra 哪裡不一樣？】
 *   Dijkstra：永遠先處理目前 dist 最小的點（需要邊權 ≥ 0）。
 *   Bellman-Ford：每一輪把「所有邊」各鬆弛一次，做滿 n-1 輪。
 *   因此可以處理負邊；代價是比較慢 O(n·m)。
 *
 * 【為什麼剛好 n-1 輪？】
 *   沒有負環時，最短路是一條「簡單路徑」（不重複點），
 *   最多只有 n-1 條邊。每輪至少能把「多用一條邊才走得到」的答案補對，
 *   所以 n-1 輪後，所有最短路都定案。
 *
 * 【第 n 輪：負環偵測】
 *   若再鬆弛一輪，某個 dist 還能變小 → 存在「從起點可達」的負環
 *   （繞一圈越走越便宜，最短路不存在）。
 *
 * 【輸入】
 *   第一行：n m s（點數、邊數、起點），點編號 1..n
 *   接下來 m 行：u v w（有向邊 u→v，權重 w，可為負）
 *   輸出：若有從 s 可達的負環 → 一行 NEGATIVE CYCLE
 *         否則 → dist[1] .. dist[n]（不可達印 -1）
 *
 * 【複雜度】O(n·m)
 * 【備註】SPFA = 用佇列優化「誰的 dist 剛變過才再鬆弛」；這份先學樸素版。
 */

#include <bits/stdc++.h>
using namespace std;

struct Edge
{
    int u, v;
    long long w;
};

int main()
{
    int n, m, s;
    cin >> n >> m >> s;

    // 邊表：Bellman-Ford 每輪要掃「所有邊」，用 list 比鄰接表直覺
    vector<Edge> edges;
    edges.reserve(m);
    for (int i = 0; i < m; i++)
    {
        int u, v;
        long long w;
        cin >> u >> v >> w;
        edges.push_back({u, v, w});
        // 無向圖再 push {v, u, w}
    }

    const long long INF = 4e18;
    vector<long long> dist(n + 1, INF);
    dist[s] = 0;

    // ---------- 主體：鬆弛 n-1 輪 ----------
    for (int round = 1; round <= n - 1; round++)
    {
        bool changed = false;
        for (auto [u, v, w] : edges)
        {
            // 起點還走不到 u 時，不能用這條邊去更新（避免 INF + 負數亂搞）
            if (dist[u] == INF)
                continue;
            if (dist[v] > dist[u] + w)
            {
                dist[v] = dist[u] + w;
                changed = true;
            }
        }
        // 某一輪完全沒更新 → 提早結束（可選優化）
        if (!changed)
            break;
    }

    // ---------- 第 n 輪：還能變短？→ 負環 ----------
    bool neg = false;
    for (auto [u, v, w] : edges)
    {
        if (dist[u] == INF)
            continue;
        if (dist[v] > dist[u] + w)
        {
            neg = true;
            break;
        }
    }

    if (neg)
    {
        cout << "NEGATIVE CYCLE\n";
        return 0;
    }

    for (int i = 1; i <= n; i++)
    {
        if (dist[i] == INF)
            cout << -1;
        else
            cout << dist[i];
        cout << (i == n ? '\n' : ' ');
    }
}

/*
 * ============================================================
 *  手跑 A：有負邊、無負環
 * ============================================================
 *
 * 輸入：
 *   4 5 1
 *   1 2 4
 *   1 3 5
 *   2 3 -3
 *   2 4 3
 *   3 4 2
 *
 * 圖：
 *         4
 *     1 -----> 2 -----> 4
 *      \       |  -3     ^
 *     5 \      v         | 2
 *        ----> 3 --------
 *
 * 初始：dist = [-, 0, ∞, ∞, ∞]
 *
 * 第 1 輪掃完全部邊後（順序可能影響「中間值」，n-1 輪後結果一樣）：
 *   經 1→2：dist[2]=4
 *   經 1→3：dist[3]=5
 *   經 2→3：4+(-3)=1 < 5 → dist[3]=1
 *   經 2→4：4+3=7 → dist[4]=7
 *   經 3→4：1+2=3 < 7 → dist[4]=3
 *
 * 之後輪次不再變短。第 n 輪無法再鬆弛 → 無負環。
 * 答案：0 4 1 3
 *
 * ============================================================
 *  手跑 B：有負環
 * ============================================================
 *
 * 輸入：
 *   3 3 1
 *   1 2 1
 *   2 3 -2
 *   3 2 0
 *
 * 2→3→2 繞一圈：-2+0 = -2 < 0，越繞越便宜。
 * n-1 輪後再掃一輪仍能更新 → 輸出 NEGATIVE CYCLE
 *
 * ============================================================
 *  記住三件事
 * ============================================================
 *  1. 鬆弛式子跟 Dijkstra 一樣，只改 dist。
 *  2. 不挑最近点；暴力掃邊 n-1 次 → 可負權。
 *  3. 多做一輪還能更新 = 從起點可達的負環。
 */
